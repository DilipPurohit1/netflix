/* =====================================================
   LIKE
===================================================== */

function setLikeState(
    movieId,
    cardButton = null
) {

    const reactions =
        getReactionData();


    if (
        reactions[movieId] ===
        "like"
    ) {

        delete reactions[
            movieId
        ];

    } else {

        reactions[movieId] =
            "like";
    }


    saveReactionData(
        reactions
    );


    if (cardButton) {

        const icon =
            cardButton.querySelector(
                "i"
            );


        cardButton.classList.toggle(
            "selected",
            isLiked(movieId)
        );


        if (icon) {

            icon.className =
                isLiked(movieId)
                    ? "fa-solid fa-thumbs-up"
                    : "fa-solid fa-thumbs-up";
        }
    }


    updateDetailLikeButtons();
}


