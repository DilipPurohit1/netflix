/* =====================================================
   MY LIST
===================================================== */

function getMyList() {

    try {

        return JSON.parse(
            localStorage.getItem(
                "myList"
            )
        ) || [];

    } catch (error) {

        console.error(
            "Could not read My List:",
            error
        );

        return [];
    }
}


function isInMyList(
    movieId
) {

    return getMyList()
        .some(
            item =>
                item.id === movieId
        );
}


function addCurrentToList() {

    toggleMovieList(
        currentMovieId
    );
}


function addToMyList(
    movieId
) {

    const movie =
        movies[movieId];


    if (!movie) {

        return;
    }


    const myList =
        getMyList();


    const exists =
        myList.some(
            item =>
                item.id === movieId
        );


    if (exists) {

        return;
    }


    myList.push({

        id:
            movieId,

        title:
            movie.title,

        label:
            movie.label,

        year:
            movie.year,

        seasons:
            movie.seasons,

        type:
            movie.type,

        age:
            movie.age,

        genres:
            movie.genres,

        poster:
            movie.poster,

        backdrop:
            movie.backdrop,

        description:
            movie.description,

        videoId:
            movie.videoId

    });


    localStorage.setItem(
        "myList",
        JSON.stringify(
            myList
        )
    );


    showToast(
        `${movie.title} added to My List`
    );
}


function removeFromMyList(
    movieId
) {

    const updated =
        getMyList()
            .filter(
                item =>
                    item.id !== movieId
            );


    localStorage.setItem(
        "myList",
        JSON.stringify(
            updated
        )
    );


    showToast(
        "Removed from My List"
    );
}


function toggleMovieList(
    movieId,
    button = null
) {

    if (
        isInMyList(
            movieId
        )
    ) {

        removeFromMyList(
            movieId
        );

    } else {

        addToMyList(
            movieId
        );
    }


    /* UPDATE CARD BUTTON */

    if (button) {

        const icon =
            button.querySelector(
                "i"
            );


        if (icon) {

            icon.className =
                isInMyList(
                    movieId
                )
                    ? "fa-solid fa-check"
                    : "fa-solid fa-plus";
        }
    }


    updateHeroListButton();

    updateDetailListButton();
}


