const searchInput =
    document.getElementById(
        "searchInput"
    );


if (searchInput) {

    searchInput.addEventListener(
        "input",
        function() {

            const query =
                this.value
                    .trim()
                    .toLowerCase();


            document
                .querySelectorAll(
                    ".movie-item"
                )
                .forEach(
                    card => {

                        const title =
                            (
                                card.dataset.title ||
                                ""
                            )
                            .toLowerCase();


                        if (
                            query === "" ||
                            title.includes(
                                query
                            )
                        ) {

                            card.style.display =
                                "";

                        } else {

                            card.style.display =
                                "none";
                        }

                    }
                );

        }
    );
}


