        document.querySelector(
            ".search-container"
        );


    if (!search) {

        return;
    }


    search.classList.toggle(
        "open"
    );


    if (
        search.classList.contains(
            "open"
        )
    ) {

        const input =
            document.getElementById(
                "searchInput"
            );


        if (input) {

            input.focus();
        }
    }
